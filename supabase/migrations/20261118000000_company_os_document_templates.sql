-- Company OS: template-first document generation.
--
-- A template now carries the metadata a document needs (company, division, type, sensitivity, who may generate it,
-- who may read what it makes, whether it needs approval and legal review, and the fields to fill in). People pick a
-- template; the rest is resolved from it.
--
--   os_doc_templates              the registry (Drive-copy templates and built-in generated documents)
--   os_doc_template_versions      a snapshot of every version of every template (history)
--   os_doc_template_authorized    named people (besides founders) who may generate a template that needs a named list
--   os_documents.template_id etc. which template and version made a document, who it is about, and who may read it
--
-- Additive only. No folder is created and no route is approved here: the two routes this adds are PROPOSED (they point at
-- the existing Personnel Records folders) and wait for a founder to approve them in Admin. The built-in Manager Offering
-- Letter is registered as "draft, pending legal review". Safe to run more than once.

-- ── Templates ──────────────────────────────────────────────────────────────────────────────────────────────────────

create table if not exists public.os_doc_templates (
  id                      text primary key check (id ~ '^[a-z0-9][a-z0-9-]{2,60}$'),
  name                    text not null check (length(trim(name)) between 1 and 120),
  description             text not null default '' check (length(description) <= 600),
  use_when                text check (use_when is null or length(use_when) <= 400),
  category                text not null check (length(trim(category)) between 1 and 60),
  doc_type                text not null check (doc_type in ('GOV', 'POL', 'SOP', 'TPL', 'PLN', 'RPT', 'MIN', 'PRP', 'CTR', 'FIN', 'REF', 'LET', 'MOM')),
  sensitivity             text not null default 'Internal' check (sensitivity in ('Internal', 'Confidential', 'Restricted')),
  company_codes           text[] not null check (cardinality(company_codes) > 0 and company_codes <@ array['HQ', 'IEL', 'ELC']),
  division_ids            text[],                                   -- null: any division the person can file for
  storage_division_id     text references public.os_divisions (id), -- set: documents are always filed under this division
  kind                    text not null check (kind in ('drive_copy', 'builtin')),
  builtin_key             text check (builtin_key is null or builtin_key in ('manager_agreement')),
  drive_template_file_id  text check (drive_template_file_id is null or drive_template_file_id ~ '^[A-Za-z0-9_-]{20,}$'),
  eligibility             text not null default 'staff' check (eligibility in ('founders', 'authorized', 'staff')),
  access_mode             text not null default 'standard' check (access_mode in ('standard', 'named')),
  approval_required       boolean not null default false,
  legal_status            text not null default 'not_required' check (legal_status in ('not_required', 'draft_pending_legal', 'legally_approved')),
  content_revision        int not null default 1,
  legal_approved_revision int,
  legal_approved_by       text references public.os_people (id),
  legal_approved_at       timestamptz,
  owner_person_id         text references public.os_people (id) on delete set null,
  fields                  jsonb not null default '[]'::jsonb check (jsonb_typeof(fields) = 'array'),
  version                 int not null default 1,
  active                  boolean not null default true,
  created_by              text,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  check (kind <> 'builtin' or builtin_key is not null),
  check (kind <> 'drive_copy' or drive_template_file_id is not null),
  -- A named-readers template is generated only by founders or the named list.
  check (access_mode <> 'named' or eligibility in ('founders', 'authorized')),
  -- Restricted documents are never generated by "any staff".
  check (sensitivity <> 'Restricted' or eligibility in ('founders', 'authorized')),
  check (legal_status <> 'legally_approved' or (legal_approved_revision is not null and legal_approved_by is not null))
);
create index if not exists os_doc_templates_active_idx on public.os_doc_templates (active, category);

create table if not exists public.os_doc_template_versions (
  template_id  text not null references public.os_doc_templates (id) on delete cascade,
  version      int not null,
  snapshot     jsonb not null,
  changed_by   text,
  changed_at   timestamptz not null default now(),
  primary key (template_id, version)
);

create table if not exists public.os_doc_template_authorized (
  template_id  text not null references public.os_doc_templates (id) on delete cascade,
  person_id    text not null references public.os_people (id) on delete cascade,
  added_by     text,
  added_at     timestamptz not null default now(),
  primary key (template_id, person_id)
);

-- ── Rules ──────────────────────────────────────────────────────────────────────────────────────────────────────────

create or replace function public.os_template_can_generate(p_template text) returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select case
      when public.os_current_person() is null or not t.active then false
      when public.os_is_founder() then true
      when t.eligibility = 'staff' then public.os_is_staff()
      when t.eligibility = 'authorized' then public.os_is_staff() and exists (
        select 1 from public.os_doc_template_authorized a where a.template_id = t.id and a.person_id = public.os_current_person())
      else false end
    from public.os_doc_templates t where t.id = p_template), false)
$$;
revoke all on function public.os_template_can_generate(text) from public, anon;
grant execute on function public.os_template_can_generate(text) to authenticated;

create or replace function public.os_doc_templates_before_write() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := public.os_current_person();
    new.created_at := now(); new.version := 1;
    if new.legal_status = 'legally_approved' then
      new.legal_approved_by := public.os_current_person(); new.legal_approved_at := now();
    end if;
  else
    new.created_by := old.created_by; new.created_at := old.created_at; new.kind := old.kind;
    new.builtin_key := old.builtin_key; new.content_revision := old.content_revision;
    -- Legal approval is recorded against the founder who gave it, for the content revision they were shown.
    if new.legal_status = 'legally_approved' and old.legal_status is distinct from 'legally_approved' then
      new.legal_approved_by := public.os_current_person(); new.legal_approved_at := now();
      new.legal_approved_revision := old.content_revision;
    elsif new.legal_status <> 'legally_approved' then
      new.legal_approved_by := null; new.legal_approved_at := null; new.legal_approved_revision := null;
    else
      new.legal_approved_by := old.legal_approved_by; new.legal_approved_at := old.legal_approved_at; new.legal_approved_revision := old.legal_approved_revision;
    end if;
    new.version := old.version;
    if (to_jsonb(new) - 'updated_at' - 'version') is distinct from (to_jsonb(old) - 'updated_at' - 'version') then
      new.version := old.version + 1;
    end if;
  end if;
  new.name := trim(new.name);
  new.updated_at := now();
  return new;
end $$;
revoke all on function public.os_doc_templates_before_write() from public, anon, authenticated;
drop trigger if exists os_doc_templates_a_rules on public.os_doc_templates;
create trigger os_doc_templates_a_rules before insert or update on public.os_doc_templates for each row execute function public.os_doc_templates_before_write();

create or replace function public.os_doc_templates_snapshot() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.os_doc_template_versions (template_id, version, snapshot, changed_by)
  values (new.id, new.version, to_jsonb(new), public.os_current_person())
  on conflict (template_id, version) do update set snapshot = excluded.snapshot, changed_by = excluded.changed_by, changed_at = now();
  return null;
end $$;
revoke all on function public.os_doc_templates_snapshot() from public, anon, authenticated;
drop trigger if exists os_doc_templates_b_snapshot on public.os_doc_templates;
create trigger os_doc_templates_b_snapshot after insert or update on public.os_doc_templates for each row execute function public.os_doc_templates_snapshot();

create or replace function public.os_doc_template_authorized_before_write() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.os_people p where p.id = new.person_id and p.org_role <> 'guest' and p.status in ('active', 'onboarding')) then
    raise exception 'Only active staff can be authorised to generate documents' using errcode = '23514';
  end if;
  new.added_by := public.os_current_person(); new.added_at := now();
  return new;
end $$;
revoke all on function public.os_doc_template_authorized_before_write() from public, anon, authenticated;
drop trigger if exists os_doc_template_authorized_a_rules on public.os_doc_template_authorized;
create trigger os_doc_template_authorized_a_rules before insert on public.os_doc_template_authorized for each row execute function public.os_doc_template_authorized_before_write();

drop trigger if exists os_doc_templates_audit on public.os_doc_templates;
create trigger os_doc_templates_audit after insert or update or delete on public.os_doc_templates for each row execute function public.os_audit_row();
drop trigger if exists os_doc_template_authorized_audit on public.os_doc_template_authorized;
create trigger os_doc_template_authorized_audit after insert or update or delete on public.os_doc_template_authorized for each row execute function public.os_audit_row();

-- ── Documents: which template made it, who it is about, who may read it ────────────────────────────────────────────

alter table public.os_documents add column if not exists template_id text references public.os_doc_templates (id);
alter table public.os_documents add column if not exists template_version int;
alter table public.os_documents add column if not exists access_mode text not null default 'standard' check (access_mode in ('standard', 'named'));
alter table public.os_documents add column if not exists subject_person_id text references public.os_people (id) on delete set null;
alter table public.os_documents add column if not exists generation_status text check (generation_status is null or generation_status in ('internal_draft', 'execution_ready'));
alter table public.os_documents add column if not exists inputs jsonb;
create index if not exists os_documents_template_idx on public.os_documents (template_id) where template_id is not null;

-- When a document is made from a template, the template decides company, type, sensitivity, division, readers and
-- draft status. The caller cannot choose a different one.
create or replace function public.os_documents_template_rules() returns trigger
language plpgsql security definer set search_path = '' as $$
declare t public.os_doc_templates;
begin
  if new.template_id is null then
    new.access_mode := 'standard'; new.template_version := null; new.generation_status := null;
    return new;
  end if;
  select * into t from public.os_doc_templates where id = new.template_id;
  if t.id is null then raise exception 'Unknown template' using errcode = '23503'; end if;
  if not public.os_template_can_generate(t.id) then raise exception 'You can''t generate documents from this template' using errcode = '42501'; end if;
  if not (new.company_code = any (t.company_codes)) then raise exception 'This template isn''t available for that company' using errcode = '23514'; end if;
  if new.doc_type <> t.doc_type or new.sensitivity <> t.sensitivity then raise exception 'The template decides the document type and sensitivity' using errcode = '23514'; end if;
  if t.storage_division_id is not null and new.division_id is distinct from t.storage_division_id then
    raise exception 'This template files its documents under one division' using errcode = '23514';
  end if;
  if t.storage_division_id is null and t.division_ids is not null and not (new.division_id = any (t.division_ids)) then
    raise exception 'This template isn''t available for that division' using errcode = '23514';
  end if;
  new.access_mode := t.access_mode;
  new.template_version := t.version;
  new.generation_status := case
    when t.legal_status = 'draft_pending_legal' then 'internal_draft'
    when t.legal_status = 'legally_approved' and t.legal_approved_revision = t.content_revision then 'execution_ready'
    when t.legal_status = 'legally_approved' then 'internal_draft'
    else null end;
  return new;
end $$;
revoke all on function public.os_documents_template_rules() from public, anon, authenticated;
drop trigger if exists os_documents_c_template on public.os_documents;
create trigger os_documents_c_template before insert on public.os_documents for each row execute function public.os_documents_template_rules();


-- A draft that is still pending legal review can't be marked Approved, so nothing generated before sign-off can pass as final.
create or replace function public.os_documents_draft_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.generation_status = 'internal_draft' and new.status = 'Approved' and (tg_op = 'INSERT' or old.status is distinct from 'Approved') then
    raise exception 'This document is an internal draft pending legal review and can''t be approved yet' using errcode = '23514';
  end if;
  return new;
end $$;
revoke all on function public.os_documents_draft_guard() from public, anon, authenticated;
drop trigger if exists os_documents_d_draft_guard on public.os_documents;
create trigger os_documents_d_draft_guard before insert or update on public.os_documents for each row execute function public.os_documents_draft_guard();

-- A named-readers document is read by founders, people with an explicit grant, the people authorised for its template,
-- and the person it is about, once a founder has approved it. Nobody else, whatever their division or workspace.
create or replace function public.os_document_named_visible(p_id text, p_template text, p_subject text, p_status text) returns boolean
language sql stable security definer set search_path = '' as $$
  select public.os_current_person() is not null and (
       public.os_is_founder()
    or public.os_has_grant('document', p_id, 'view')
    or (p_subject is not null and p_subject = public.os_current_person() and p_status = 'Approved')
    or (p_template is not null and public.os_is_staff() and exists (
          select 1 from public.os_doc_template_authorized a where a.template_id = p_template and a.person_id = public.os_current_person())))
$$;
revoke all on function public.os_document_named_visible(text, text, text, text) from public, anon;
grant execute on function public.os_document_named_visible(text, text, text, text) to authenticated;

drop policy if exists os_documents_read on public.os_documents;
create policy os_documents_read on public.os_documents for select to authenticated
  using (case when access_mode = 'named' then public.os_document_named_visible(id, template_id, subject_person_id, status)
              else public.os_can_view(company_code, division_id, sensitivity, 'document', id)
                   or (public.os_is_staff() and owner_person_id = public.os_current_person()) end);

-- Updates keep their existing policy; Postgres also applies the read policy above, so a named document can only be
-- changed by someone who can read it.
drop policy if exists os_documents_insert_template on public.os_documents;
create policy os_documents_insert_template on public.os_documents for insert to authenticated
  with check (template_id is not null and public.os_template_can_generate(template_id)
              and owner_person_id = public.os_current_person() and status = 'Draft' and public.os_in_company(company_code));
grant insert (template_id, subject_person_id) on public.os_documents to authenticated;

