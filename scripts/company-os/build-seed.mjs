// Builds supabase/migrations/20261108010000_company_os_kpi_timeline_data.sql from the Operations Master exports in
// supabase/seed-data/company-os/*.json (KPI_Dictionary, KPI_Log, Master_Timeline, read 2026-11-07).
// Mapping rules: IDs are kept as they are; no value is invented (blank stays null); targets only where the sheet has
// one, with its target status; the sheet's live-calculated "Latest Value" is kept as a labelled snapshot, not as a
// logged KPI value. Run: node scripts/company-os/build-seed.mjs  (then node scripts/company-os/build-seed.mjs --check)
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const dir = path.join(root, "supabase/seed-data/company-os");
const out = path.join(root, "supabase/migrations/20261108010000_company_os_kpi_timeline_data.sql");
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
const kpiSrc = read("kpi_dictionary.2026-11-07.json");
const tlSrc = read("master_timeline.2026-11-07.json");
const logSrc = read("kpi_log.2026-11-07.json");

const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const date = (v) => (/^\d{4}-\d{2}-\d{2}$/.test(v ?? "") ? `'${v}'` : "null");
const num = (v) => (v !== "" && v != null && /^-?\d+(\.\d+)?$/.test(String(v).trim()) ? String(Number(v)) : "null");
const COMPANY = { HQ: "HQ", IELSco: "IEL", Elco: "ELC" };
const DIVISION = { Community: "DIV-01", Operations: "DIV-02", Growth: "DIV-03", Creative: "DIV-04", People: "DIV-05", Partnerships: "DIV-06", "Courses & Learning": "DIV-07" };
const col = (i) => (i < 26 ? String.fromCharCode(65 + i) : "A" + String.fromCharCode(65 + i - 26));
// Only the source columns that have no column of their own are kept in "source" (every other column is mapped 1:1).
const sourceJson = (headers, row, idx) => {
  const o = {};
  idx.forEach((i) => { if (row[i]) o[`${col(i)} ${headers[i]}`] = row[i]; });
  return Object.keys(o).length ? `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb` : "null";
};
const problems = [];

// ── KPIs
const kh = kpiSrc.values[0];
const kpis = kpiSrc.values.slice(1).map((r) => {
  const company = COMPANY[r[1]];
  if (!company) problems.push(`${r[0]}: unknown entity ${r[1]}`);
  if (!/^KPI-\d{4}$/.test(r[0])) problems.push(`bad KPI id ${r[0]}`);
  const owner = (r[13].match(/PPL-\d{4}/) || [null])[0];
  const restricted = /^Restricted/.test(r[22]);  // "Measurable Today?" = "Restricted — Finance Control"
  return `(${[q(r[0]), q(company), q(r[2]), q(r[3]), q(r[4]), q(r[5]), q(r[6]), q(r[7]), q(r[8]), q(r[9]), q(r[10]), q(r[11]), q(r[12]),
    q(r[13]), q(owner), q(r[14]), num(r[15]), q(r[16]), q(r[17]), q(r[18]), q(r[19]), q(r[20]), q(r[21]), q(r[22]), q(r[23]), date(r[24]),
    q(r[25]), q(r[26]), q(r[27]), q(r[30]), q(r[31]), restricted, sourceJson(kh, r, [28, 29])].join(", ")})`;
});

// ── Timeline
const th = tlSrc.values[0];
const tl = tlSrc.values.slice(1).map((r) => {
  const m = r[4].match(/^(WS\d+)\s+(.*)$/);
  if (!m) problems.push(`${r[0]}: workstream ${r[4]}`);
  if (!/^TL-\d{3}$/.test(r[0])) problems.push(`bad TL id ${r[0]}`);
  if (!["Not started", "In progress", "Done", "Blocked", "Deferred", "Cancelled"].includes(r[13])) problems.push(`${r[0]}: status ${r[13]}`);
  if (r[11] && r[12] && r[12] < r[11]) problems.push(`${r[0]}: due before start`);
  const lead = DIVISION[r[24]] ?? null;
  if (r[24] && !lead && r[24] !== "Founders") problems.push(`${r[0]}: lead division ${r[24]}`);
  return `(${[q(r[0]), q(m?.[1]), q(m?.[2]), q(r[5]), q(r[6]), q(r[7]), q(r[8]), q(r[24]), q(lead), q(r[9]), q(r[10]), date(r[11]), date(r[12]),
    q(r[13]), q(r[14]), q(r[15]), q(r[16]), q(r[17]), q(r[18]), q(r[19]), r[20] === "Yes", q(r[21]), sourceJson(th, r, [1])].join(", ")})`;
});

const logs = logSrc.values.slice(1);
if (logs.length) problems.push(`KPI_Log has ${logs.length} rows: add a mapping before migrating them`);
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

const kpiIds = kpiSrc.values.slice(1).map((r) => r[0]);
const tlIds = tlSrc.values.slice(1).map((r) => r[0]);
const sql = `-- Company OS data: the KPI Dictionary (${kpis.length} KPIs) and the Master Timeline (${tl.length} items) from Operations Master
-- (spreadsheet 1squ61BolAnFuisz1d5y3mKQe8-DYN7Vc_BkEMT-qbUc), read on 2026-11-07. KPI_Log had no rows, so no values are loaded.
-- GENERATED by scripts/company-os/build-seed.mjs from supabase/seed-data/company-os/*.json; do not edit by hand.
-- Backups of the source rows: supabase/seed-data/company-os/ (sha256 in the project's backups folder).
-- IDs are kept. Re-runnable: rows that already exist are left as they are (on conflict do nothing), so running it twice
-- creates no duplicates and never overwrites edits made in Company OS.

insert into public.os_kpis (id, company_code, level, function, name, business_purpose, definition, formula, indicator_type, unit,
  reporting_period, data_source, collection_method, owner_text, owner_person_id, baseline, target_value, target_status,
  reference_target, green_threshold, amber_threshold, red_threshold, action_when_missed, measurable_today, sheet_latest_value,
  sheet_latest_period_end, data_status, notes, review_forum, track_now, start_condition, values_restricted, source)
values
${kpis.join(",\n")}
on conflict (id) do nothing;

insert into public.os_timeline_items (id, workstream_code, workstream_name, title, deliverable, owner_person_id, owner_name,
  lead_division, lead_division_id, supporting_divisions, dependencies, planned_start, due_date, status, decision_gate,
  budget_dependency, evidence, risk, related_event, linked_refs, is_major, planning_label, source)
values
${tl.join(",\n")}
on conflict (id) do nothing;

-- Completeness check: every source ID is present, and counters are past the highest ID.
do $$
declare missing text;
begin
  select string_agg(i, ', ') into missing from unnest(array[${kpiIds.map(q).join(",")}]) i
  where not exists (select 1 from public.os_kpis k where k.id = i);
  if missing is not null then raise exception 'KPI rows missing after load: %', missing; end if;
  select string_agg(i, ', ') into missing from unnest(array[${tlIds.map(q).join(",")}]) i
  where not exists (select 1 from public.os_timeline_items t where t.id = i);
  if missing is not null then raise exception 'Timeline rows missing after load: %', missing; end if;
  update public.os_id_counters set last = greatest(last, ${kpiIds.length}) where prefix = 'KPI';
  update public.os_id_counters set last = greatest(last, ${Math.max(...tlIds.map((i) => Number(i.slice(3))))}) where prefix = 'TL';
end $$;
`;
if (process.argv.includes("--check")) {
  const cur = fs.readFileSync(out, "utf8");
  if (cur !== sql) { console.error("seed migration is out of date: run node scripts/company-os/build-seed.mjs"); process.exit(1); }
  console.log("seed migration matches the source JSON");
} else {
  fs.writeFileSync(out, sql);
  console.log(`wrote ${path.relative(root, out)}: ${kpis.length} KPIs, ${tl.length} timeline items`);
}
